/**
 * Portadas de marcador para las entradas sintéticas (group y dbatch).
 *
 * Aniyomi solo carga portadas desde una URL http(s) o desde un archivo local, así que las imágenes
 * viajan dentro de la extensión (PNG en Base64) y se copian a un archivo del almacenamiento interno
 * de la app la primera vez que hacen falta. Si el archivo desaparece, se vuelve a crear solo.
 */
internal object NyaaCovers {
    // Subir VERSION si se cambian las imágenes: cambia el nombre del archivo y las apps no
    // reutilizan la portada anterior desde su caché de imágenes.
    private const val VERSION = 1

    // mode: 0 = agrupar todo, 1 = priorizar versión más alta ("v ↑"), 2 = ignorar nuevas versiones ("v 1").
    fun groupUrl(mode: Int): String? = when (mode) {
        1 -> coverUrl("group_latest", GROUP_LATEST)
        2 -> coverUrl("group_original", GROUP_ORIGINAL)
        else -> coverUrl("group", GROUP)
    }

    fun batchUrl(): String? = coverUrl("batch", BATCH)

    private fun coverUrl(name: String, base64: String): String? = try {
        val dir = File(applicationContext.filesDir, "nyaatorrent_covers").apply { mkdirs() }
        val file = File(dir, "${name}_v$VERSION.png")
        if (!file.exists() || file.length() == 0L) {
            // Se escribe a un archivo temporal y se renombra: nunca queda una imagen a medias.
            val tmp = File(dir, "${name}_v$VERSION.tmp")
            tmp.writeBytes(Base64.decode(base64, Base64.DEFAULT))
            tmp.renameTo(file)
        }
        if (file.exists()) "file://${file.absolutePath}" else null
    } catch (e: Exception) {
        null
    }

